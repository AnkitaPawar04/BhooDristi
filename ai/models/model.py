def predict_by_district(district, season):

    district = district.lower().strip()
    season = season.lower().strip()

    # Validate district
    if district not in district_soil["District"].values:
        return {"Error": "District not found"}

    # Get soil values
    soil = district_soil[district_soil["District"] == district].iloc[0]

    N = float(soil["N"])
    P = float(soil["P"])
    K = float(soil["K"])
    ph = float(soil["ph"])

    # Seasonal weather defaults
    weather_defaults = {
        "kharif": {"temperature": 28, "humidity": 80, "rainfall": 200},
        "rabi": {"temperature": 22, "humidity": 60, "rainfall": 50},
        "zaid": {"temperature": 34, "humidity": 40, "rainfall": 20}
    }

    if season not in weather_defaults:
        return {"Error": "Invalid season"}

    weather = weather_defaults[season]

    temperature = weather["temperature"]
    humidity = weather["humidity"]
    rainfall = weather["rainfall"]

    # Prepare model input
    input_data = pd.DataFrame(
        [[N, P, K, temperature, humidity, ph, rainfall]],
        columns=features
    )

    # Predict probabilities
    probs = rf_model.predict_proba(input_data)[0]
    classes = rf_model.classes_

    # Filter crops by season
    allowed = season_crops.get(season, [])

    filtered = []

    for i in probs.argsort()[::-1]:
        crop = classes[i]

        if crop in allowed:
            filtered.append((crop, probs[i]))

        if len(filtered) == 3:
            break

    if len(filtered) == 0:
        return {"Error": "No suitable crops found"}

    # Normalize probabilities
    prob_sum = sum(p for _, p in filtered)

    recommendations = []
    for crop, prob in filtered:

        normalized = (prob / prob_sum) * 100

        recommendations.append({
            "Crop": crop,
            "Confidence (%)": round(float(normalized),2)
        })

    best_crop = recommendations[0]["Crop"]
    confidence = recommendations[0]["Confidence (%)"]

    # SHAP Explanation
    shap_values = explainer.shap_values(input_data)

    class_index = list(classes).index(best_crop)

    shap_contrib = shap_values[0,:,class_index]

    shap_df = pd.DataFrame({
        "Feature": features,
        "Contribution": shap_contrib
    }).sort_values(by="Contribution", key=abs, ascending=False)

    top_features = shap_df.head(3)

    explanations = []

    for _, row in top_features.iterrows():

        feature = row["Feature"]

        explanations.append(
            feature_explanations.get(
                feature,
                f"{feature} influenced the recommendation."
            )
        )

    return {
        "District": district.title(),
        "Season": season.title(),
        "Recommended Crop": best_crop,
        "Confidence (%)": confidence,
        "Top 3 Crops": recommendations,
        "Agronomic Insight": crop_knowledge.get(best_crop, ""),
        "Key Factors": explanations
    }

