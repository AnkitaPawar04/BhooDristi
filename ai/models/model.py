def BhooDristi_predict(district_name):

    district_name = district_name.lower().strip()

    # Check district existence
    if district_name not in district_features.index:
        return {
            "Error": "District not found in BhooDristi database."
        }

    # Extract district row
    row = district_features.loc[district_name]

    # Prepare model input
    input_data = pd.DataFrame([[
        row["Nitrogen_Score"],
        row["Phosphorous_Score"],
        row["Potassium_Score"],
        row["pH - Acidic"],
        row["pH - Neutral"],
        row["pH - Alkaline"],
        row["Latitude"],
        row["Longitude"]
    ]], columns=feature_columns)

    # Make prediction
    predicted_crop = model.predict(input_data)[0]
    probabilities = model.predict_proba(input_data)[0]

    # Confidence
    confidence = float(round(max(probabilities) * 100, 2))

    # Top 3 recommendations
    classes = model.classes_
    top3_idx = probabilities.argsort()[-3:][::-1]

    top3 = []
    for idx in top3_idx:
        top3.append({
            "Crop": classes[idx],
            "Confidence (%)": float(round(probabilities[idx] * 100, 2))
        })

    # Final output (API-ready JSON format)
    return {
        "District": district_name.title(),
        "Primary Recommendation": predicted_crop,
        "Confidence (%)": confidence,
        "Top 3 Recommendations": top3
    }

